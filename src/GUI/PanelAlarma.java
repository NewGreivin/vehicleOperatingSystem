    private void btnAlarmaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlarmaActionPerformed
        if(simulador.getVehiculo().getAlarma().isActiva()){
            simulador.getVehiculo().getAlarma().desactivarAlarma();
            btnAlarma.setText("Encender alarma");
        }else{
            simulador.getVehiculo().getAlarma().activarAlarma();
            btnAlarma.setText("Apagar alarma");
        }
    }//GEN-LAST:event_btnAlarmaActionPerformed

    private void btnCierreActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCierreActionPerformed
        if( simulador.getVehiculo().getPuertas().isBloqueada()){
            simulador.getVehiculo().getPuertas().abrir();
            btnCierre.setText("Cerrar cierre");
        }else{
            simulador.getVehiculo().getPuertas().bloquear();
            btnCierre.setText("Abrir cierre");
        }
    }//GEN-LAST:event_btnCierreActionPerformed


